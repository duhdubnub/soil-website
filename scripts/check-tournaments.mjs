import assert from 'node:assert/strict';
import {display,description,dateValue,externalUrl,eventSchema,serializeSchema} from '../src/lib/tournaments.mjs';
for(const value of [null,undefined,'','   ',[]])assert.equal(display(value),'To be announced');
assert.equal(display(0),'0');assert.equal(display(['B','C']),'B, C');
assert.equal(dateValue('2027-02-30'),null);assert.equal(dateValue('tomorrow'),null);
assert.equal(dateValue('2027-01-09').label,'January 9, 2027');
assert.equal(dateValue('2027-01-09T09:00:00-06:00').iso,'2027-01-09T09:00:00-06:00');
assert.equal(externalUrl('javascript:alert(1)'),null);assert.equal(externalUrl(''),null);
assert.equal(externalUrl('https://example.org/register'),'https://example.org/register');
const t={id:'2027-soil-invitational',name:'2027 SOIL Invitational',date:null,location:null};
assert(description(t).includes('hosted by Science Olympiad at Illinois'));
assert.equal(eventSchema(t),null);assert.equal(eventSchema({...t,date:'2027-01-09'}),null);assert.equal(eventSchema({...t,location:'Example venue'}),null);
const schema=eventSchema({...t,date:'2027-01-09',location:'Example venue'});
assert.equal(schema.startDate,'2027-01-09');assert.equal(schema.location.name,'Example venue');
assert(!serializeSchema({...schema,name:'</script><script>alert(1)</script>'}).includes('<'));
console.log('Passed: tournament empty fields, date validation, safe URLs, conditional Event schema and script escaping.');
